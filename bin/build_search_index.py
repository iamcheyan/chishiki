#!/usr/bin/env python3
"""
事前に検索インデックスを生成するスクリプト。

実行方法:
    python3 tools/build_search_index.py --docs-dir ./docs

生成物:
    assets/search-index.js  (window.__DOCS_INDEX__ に配列としてエクスポート)

設計方針:
  - `_sidebar.md` に載っているローカル Markdown のみを対象にする。
  - Markdown をざっくりプレーンテキスト化して全文検索用フィールド `content` に格納。
  - 日本語・記号はそのまま保持し、検索側で単純な部分一致を行う。
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Iterable, List, Tuple, Optional
import argparse
import os


RE_MD_LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
RE_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")


def resolve_docs_dir(value: Optional[str]) -> Path:
    base_dir = Path(__file__).resolve().parent
    if value:
        docs_dir = Path(value).expanduser()
    else:
        env_dir = os.environ.get("DOCS_DIR")
        docs_dir = Path(env_dir).expanduser() if env_dir else base_dir.parent / "docs"

    if not docs_dir.is_absolute():
        docs_dir = (Path.cwd() / docs_dir).resolve()

    if docs_dir.exists() and not docs_dir.is_dir():
        raise NotADirectoryError(f"docs ディレクトリがファイルです: {docs_dir}")

    docs_dir.mkdir(parents=True, exist_ok=True)
    return docs_dir


def iter_links(sidebar: Path) -> Iterable[Tuple[str, str]]:
    """_sidebar.md から (タイトル, パス) を抽出する。外部リンクは除外。"""
    if not sidebar.exists():
        return []

    seen = set()
    lines = sidebar.read_text(encoding="utf-8").splitlines()
    for line in lines:
        for title, path in RE_MD_LINK.findall(line):
            if path.startswith(("http://", "https://")):
                continue
            key = (title.strip(), path.strip())
            if key not in seen:
                seen.add(key)
                yield key


def strip_markdown(text: str) -> str:
    """Markdown をざっくり平文化する。"""
    text = re.sub(r"```[\s\S]*?```", " ", text)  # コードブロック
    text = re.sub(r"`[^`]*`", " ", text)  # インラインコード
    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", " ", text)  # 画像
    text = re.sub(r"\[[^\]]*\]\([^)]+\)", " ", text)  # リンク
    text = re.sub(r"<[^>]+>", " ", text)  # HTML タグ
    text = re.sub(r"[#>*\-]{1,3}\s*", " ", text)  # 見出しや箇条書き記号
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def build_index(base_dir: Path) -> List[dict]:
    entries: List[dict] = []
    sidebar = base_dir / "_sidebar.md"
    for sidebar_title, rel_path in iter_links(sidebar):
        md_path = base_dir / rel_path
        if not md_path.exists():
            # サイドバーにあるが実ファイルが無い場合はスキップ
            continue

        raw = md_path.read_text(encoding="utf-8", errors="ignore")
        heading_match = re.search(r"^#\s*(.+)$", raw, flags=re.MULTILINE)
        title = (heading_match.group(1).strip() if heading_match else sidebar_title).strip()
        content = strip_markdown(raw)

        # セクション見出しを抽出し、url#id で直接飛べるようにする
        sections = []
        for line in raw.splitlines():
            m = RE_HEADING.match(line.strip())
            if not m:
                continue
            level = len(m.group(1))
            text = m.group(2).strip()
            if not text:
                continue
            # Docsify/marked の slugify 互換に近い簡易版
            slug = re.sub(r"[^\w\s-]", "", text).strip().lower()
            slug = re.sub(r"\s+", "-", slug)
            sections.append(
                {
                    "title": text,
                    "id": slug,
                    "level": level,
                    "url": f"{rel_path}#{slug}",
                }
            )

        entries.append(
            {
                "title": title or sidebar_title or rel_path,
                "url": rel_path,
                "content": content,
                "sections": sections,
            }
        )

    return entries


def write_index(base_dir: Path, entries: List[dict]) -> None:
    output = base_dir / "assets" / "search-index.js"
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as fp:
        fp.write("// Auto-generated by tools/build_search_index.py\n")
        fp.write("window.__DOCS_INDEX__ = ")
        json.dump(entries, fp, ensure_ascii=False)
        fp.write(";\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--docs-dir", default=None)
    args = parser.parse_args()

    base_dir = resolve_docs_dir(args.docs_dir)
    entries = build_index(base_dir)
    write_index(base_dir, entries)
    print(f"Generated {len(entries)} entries -> {Path('assets') / 'search-index.js'}")


if __name__ == "__main__":
    main()
